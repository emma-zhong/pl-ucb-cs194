"""Build the STAR copies of the English-to-SQL questions from this repository.

STAR questions cannot use course elements, so each copy inlines its element: the
element's Python goes into the question's server.py, its JavaScript and CSS into
clientFilesQuestion/, and its template into serverFilesQuestion/. Edit the element and
question here, then rerun:

    python scripts/build_star_questions.py ../pl-ucb-star-assessments

Each STAR question's existing info.json is kept, so its UUID does not change.
"""

import argparse
import ast
import os
import re
import shutil

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STAR_SUBDIR = os.path.join("questions", "EnglishToSql")
QUESTIONS = {
    "english-to-sql-transactions": "pl-intent-console",
    "english-to-sql-transactions-dictionary": "pl-intent-console-dictionary",
    "english-to-sql-transactions-regen": "pl-intent-console-regen",
    "english-to-sql-transactions-two-pass": "pl-intent-console-two-pass",
}
LIFECYCLE = ("prepare", "render", "parse", "grade")
TEMPLATE_OPEN = 'with open(TEMPLATE_FILE, encoding="utf-8") as file:'

WRAPPERS = '''

# --- Question lifecycle: run the inlined element on ELEMENT_HTML ---------------------

PLACEHOLDER = re.compile(r"<div[^>]*data-pl-intent-console-placeholder[^>]*>\\s*</div>")


def prepare(data):
    _element_prepare(ELEMENT_HTML, data)


def render(data, html):
    if not PLACEHOLDER.search(html):
        raise ValueError(
            "question.html is missing the data-pl-intent-console-placeholder div."
        )
    console = _element_render(ELEMENT_HTML, data)
    return PLACEHOLDER.sub(lambda _match: console, html, count=1)


def parse(data):
    _element_parse(ELEMENT_HTML, data)


def grade(data):
    _element_grade(ELEMENT_HTML, data)
    pl.set_weighted_score_data(data)
'''


def read(path):
    with open(path, encoding="utf-8") as file:
        return file.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write(text)


def element_tag(question_html, element):
    match = re.search(rf"<{element}\b.*?</{element}>", question_html, flags=re.DOTALL)
    if not match:
        raise SystemExit(f"<{element}> not found in question.html")
    return match


def inline_element(element):
    source = read(os.path.join(REPO, "elements", element, f"{element}.py"))
    if source.count(TEMPLATE_OPEN) != 1:
        raise SystemExit(f"{element}: expected one template open() to redirect")
    source = source.replace(
        TEMPLATE_OPEN,
        'with open(_question_file(data, TEMPLATE_FILE), encoding="utf-8") as file:',
    )
    lines = source.split("\n")
    names = {
        node.lineno - 1: node.name
        for node in ast.parse(source).body
        if isinstance(node, ast.FunctionDef) and node.name in LIFECYCLE
    }
    if sorted(names.values()) != sorted(LIFECYCLE):
        raise SystemExit(f"{element}: missing a lifecycle function")
    for index, name in names.items():
        lines[index] = lines[index].replace(f"def {name}(", f"def _element_{name}(", 1)
    return "\n".join(lines)


def question_generate(question):
    source = read(os.path.join(REPO, "questions", question, "server.py"))
    tree = ast.parse(source)
    if [type(node) for node in tree.body] != [ast.FunctionDef] or tree.body[0].name != "generate":
        raise SystemExit(f"{question}/server.py should contain only generate()")
    return source.strip()


def build(question, element, star_root):
    source_dir = os.path.join(REPO, "questions", question)
    target = os.path.join(star_root, STAR_SUBDIR, question)
    question_html = read(os.path.join(source_dir, "question.html"))
    tag = element_tag(question_html, element)

    server = (
        f'"""Generated by pl-ucb-cs194/scripts/build_star_questions.py from\n'
        f"elements/{element} and questions/{question}. Do not edit by hand.\n"
        f'"""\n\n'
        + inline_element(element).rstrip()
        + "\n\n\n# --- Question --------------------------------------------------------------------\n\n"
        + f'ELEMENT_HTML = """{tag.group(0)}"""\n\n\n'
        + question_generate(question)
        + "\n"
        + WRAPPERS
    )
    ast.parse(server)
    write(os.path.join(target, "server.py"), server)

    console = (
        f'<link rel="stylesheet" href="{{{{options.client_files_question_url}}}}/{element}.css">\n'
        "<pl-question-panel>\n"
        f'  <script src="{{{{options.client_files_question_url}}}}/{element}.js"></script>\n'
        "</pl-question-panel>\n\n"
        "<!-- Replaced by server.py render() with the intent console for the current panel.\n"
        "     The element's settings live in ELEMENT_HTML in server.py. -->\n"
        "<div data-pl-intent-console-placeholder></div>"
    )
    write(
        os.path.join(target, "question.html"),
        question_html[: tag.start()] + console + question_html[tag.end():],
    )

    for folder in ("clientFilesQuestion", "serverFilesQuestion"):
        shutil.rmtree(os.path.join(target, folder), ignore_errors=True)
    element_dir = os.path.join(REPO, "elements", element)
    for extension in ("js", "css"):
        name = f"{element}.{extension}"
        os.makedirs(os.path.join(target, "clientFilesQuestion"), exist_ok=True)
        shutil.copyfile(
            os.path.join(element_dir, name),
            os.path.join(target, "clientFilesQuestion", name),
        )
    shutil.copytree(
        os.path.join(source_dir, "serverFilesQuestion"),
        os.path.join(target, "serverFilesQuestion"),
    )
    shutil.copyfile(
        os.path.join(element_dir, f"{element}.mustache"),
        os.path.join(target, "serverFilesQuestion", f"{element}.mustache"),
    )
    if not os.path.exists(os.path.join(target, "info.json")):
        shutil.copyfile(
            os.path.join(source_dir, "info.json"), os.path.join(target, "info.json")
        )
    print(f"built {os.path.relpath(target, star_root)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("star_repo", help="path to the pl-ucb-star-assessments checkout")
    star_root = os.path.abspath(parser.parse_args().star_repo)
    if not os.path.isdir(os.path.join(star_root, STAR_SUBDIR)):
        raise SystemExit(f"{os.path.join(star_root, STAR_SUBDIR)} does not exist")
    for question, element in QUESTIONS.items():
        build(question, element, star_root)


if __name__ == "__main__":
    main()
